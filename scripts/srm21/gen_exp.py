#!/usr/bin/env python3
# Generates Tests/Compiler/Srm21ExpStmt.lean: EXPECTED full statements of the SRM21 definitions/theorems, derived ONLY from
#   SOURCE A: scripts/srm21/EXPECTED.txt (fixed and committed BEFORE any proof file): the defs GrandInstFree, QGrandInstFree, GkCorr, KidCorr and the statements of P2 (runModuleTG_depth2_depth1_of_grandInstFree), P3 (resetNk_depth_lift), P4 (qDepthLift_of_grandInstFree);
#   SOURCE B: Tests/Compiler/Srm12CorrTest.lean `topshareQ_corr` (its binder list = the premises of the topshareQ instance theorems; the conclusion is replaced by QGrandInstFree raw D b / QDepthLift raw D b);
#   SOURCE C: Tests/Compiler/Srm20BridgeTest.lean `topshareQ_svBoundsH_underComposedG` (SRM20, accepted): the corollary's statement is C with the single binder `hlift` DELETED (deletion list: D1 hlift).
# Never reads the SRM21 theorems.  Also emits MUTATIONS that the audit must reject: Exp_mut_P2_noHf (instance-free hypothesis dropped), Exp_mut_P2_depth (depth 2 of the run swapped to 1),
# Exp_mut_P3_noHf, Exp_mut_Q_firstConjunct (only the shipped-body half of QGrandInstFree), Exp_mut_corollary_withHlift (the SRM20 statement itself).
import re,sys
def groups(sig):
    out=[];i=0;n=len(sig)
    while i<n:
        c=sig[i]
        if c in '({[':
            d=0;j=i
            while True:
                if sig[j] in '({[': d+=1
                elif sig[j] in ')}]': d-=1
                if d==0: break
                j+=1
            out.append(sig[i:j+1]);i=j+1
        elif c==':' and sig[i+1]!='=': return out,sig[i+1:].strip()
        else: i+=1
def bname(g):
    m=re.match(r"[({\[]\s*([^\s:]+)",g); return m.group(1) if m else None
def sig_of(f,name):
    s=open(f).read(); m=re.search(r'^theorem '+name+r'\b(.*?) :=',s,re.S|re.M); return m.group(1)
exp=open('scripts/srm21/EXPECTED.txt').read()
def block(kind,name):
    m=re.search(r'^'+kind+' '+name+r'\b.*?(?=\n\n|\n--|\n(?:def|theorem) |\Z)',exp,re.S|re.M); assert m,name; return m.group(0)
def rn(s):
    for n in ['QGrandInstFree','GrandInstFree','GkCorr','KidCorr']: s=re.sub(r'(?<![A-Za-z_.])'+n+r'\b','Exp_'+n,s)
    return s
defs=[rn(block('def',n)).replace('def '+'Exp_'+n if False else 'def Exp_'+n,'def Exp_'+n) for n in ['GrandInstFree','QGrandInstFree','GkCorr','KidCorr']]
for d in defs: assert d.startswith('def Exp_'),d[:40]
def thm_def(name,newname):
    t=block('theorem',name)
    t=re.sub(r'--[^\n]*','',t)   # strip line comments
    sig=t[len('theorem '+name):]
    gs,concl=groups(sig)
    return gs,rn(concl)
def build(name,gs,concl): return f"def {name} : Prop :=\n  ∀ {' '.join(rn(g) for g in gs)},\n    {concl}\n"
hdr=[l for l in open('Tests/Compiler/Srm20BridgeTest.lean').read().split('\n') if l.startswith('open ')]
out=['import Tests.Compiler.Srm21LiftTest','-- GENERATED by scripts/srm21/gen_exp.py from scripts/srm21/EXPECTED.txt, the SRM12 `topshareQ_corr` source statement and the SRM20 `topshareQ_svBoundsH_underComposedG` source statement; do not edit by hand.',
     'set_option autoImplicit false','namespace Tests.Compiler.Srm21ExpStmt']+hdr+['open Tests.Compiler.Srm9ComposedTest','open Tools.ShippingMixedSourceBridge (SourceInputs)',
     'open Tools.ShippingHierStateG (KT KSn KState runModuleTG instFree)','open Tools.ShippingHierState (KidState)','open Tools.ShippingMachineShipsDepth (ResetNk)',
     'open Tests.Compiler.SharedLeafMemKidIfaceTest (QDepthLift)','open Tests.Compiler.Srm12CorrTest','open Sparkle.IR.ModuleName (ofDecl)','']
out+= [d+'\n' for d in defs]
g2,c2=thm_def('runModuleTG_depth2_depth1_of_grandInstFree','')
g3,c3=thm_def('resetNk_depth_lift','')
g4,c4=thm_def('qDepthLift_of_grandInstFree','')
out.append(build('Exp_P2',g2,c2)); out.append(build('Exp_P3',g3,c3)); out.append(build('Exp_P4',g4,c4))
# mutations
hf2=[g for g in g2 if bname(g)=='hf']; assert len(hf2)==1
out.append(build('Exp_mut_P2_noHf',[g for g in g2 if bname(g)!='hf'],c2))
lhs,rhs=c2.split(' =\n',1)
out.append(build('Exp_mut_P2_depth',g2,rhs.strip()+' =\n    '+lhs.strip()))   # depth-1 run on the left, depth-2 run on the right (sides swapped)
hf3=[g for g in g3 if bname(g)=='hf']; assert len(hf3)==1
out.append(build('Exp_mut_P3_noHf',[g for g in g3 if bname(g)!='hf'],c3))
# topshareQ instance theorems
gsB,_=groups(sig_of('Tests/Compiler/Srm12CorrTest.lean','topshareQ_corr'))
vars=['{mctx : Lean.Meta.Context}','{mref : ST.Ref IO.RealWorld Lean.Meta.State}','{cctx : Lean.Core.Context}','{cref : ST.Ref IO.RealWorld Lean.Core.State}']   # the section `variable`s of Srm12CorrTest
gsB=vars+gsB
out.append(build('Exp_topshareQ_grandInstFree',gsB,'Exp_QGrandInstFree raw D b'))
out.append(build('Exp_topshareQ_qDepthLift',gsB,'QDepthLift raw D b'))
out.append(build('Exp_mut_Q_firstConjunct',gsB,'Exp_GrandInstFree D (checkedOptimize b).body'))
# corollary
gsC,cC=groups(sig_of('Tests/Compiler/Srm20BridgeTest.lean','topshareQ_svBoundsH_underComposedG'))
assert [bname(g) for g in gsC].count('hlift')==1
out.append(build('Exp_corollary',[g for g in gsC if bname(g)!='hlift'],cC))
out.append(build('Exp_mut_corollary_withHlift',gsC,cC))
out.append('end Tests.Compiler.Srm21ExpStmt')
open('Tests/Compiler/Srm21ExpStmt.lean','w').write('\n'.join(out)+'\n')
print('D1 hlift; mutations: noHf, depth, P3 noHf, firstConjunct, withHlift')
