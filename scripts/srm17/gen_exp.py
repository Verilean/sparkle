#!/usr/bin/env python3
# Generates Tests/Compiler/Srm17ExpStmt.lean: the EXPECTED statements of the SRM17 corollaries and of the four residual-fact theorems per design, derived ONLY from the SRM16 `_viaResetState`
# SOURCE statements (Tests/Compiler/Srm16ParentTest.lean) by the explicit lists below.  Never reads SRM17 Lean sources or the theorems under audit.
import re
DELETE = ['hIUraw', 'hIU', 'hAg', 'hRd']      # corollaries: these four binders deleted (nothing inserted, nothing reordered)
HO_UP_TO = 'hw'                                # residual-fact theorems: the binders of the source up to and including hw; conclusion = the type of the source's binder of that name
print('corollary: delete', DELETE, '; residual theorems: binders up to', HO_UP_TO, ', conclusion = the type of the source binder')

def groups(sig):
    out = []; i = 0; n = len(sig)
    while i < n:
        c = sig[i]
        if c in '({[':
            depth = 0; j = i
            while True:
                if sig[j] in '({[': depth += 1
                elif sig[j] in ')}]': depth -= 1
                if depth == 0: break
                j += 1
            out.append(sig[i:j + 1]); i = j + 1
        elif c == ':' and sig[i + 1] != '=':
            return out, sig[i + 1:].strip()
        else: i += 1
    raise SystemExit('no colon')
def bname(g):
    m = re.match(r'[({\[]\s*([^\s:]+)', g); return m.group(1) if m else None
src = open('Tests/Compiler/Srm16ParentTest.lean').read()
def sig_of(name):
    m = re.search(r'^theorem ' + name + r'\b(.*?) :=', src, re.S | re.M); return m.group(1)
VARS = '∀ {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State},'
def build(name, gs, concl):
    return f"def {name} : Prop :=\n  {VARS}\n  ∀ {' '.join(gs)},\n    {concl}\n"
out = ['import Tests.Compiler.Srm16ParentTest', '-- GENERATED by scripts/srm17/gen_exp.py from the SRM16 source statements; do not edit by hand.',
       'set_option autoImplicit false', 'namespace Tests.Compiler.Srm17ExpStmt', 'open Lean Meta',
       'open Tools.ShippingEntrySoundness Tools.ShippingMachineEntry Tools.ShippingChildInvA Tools.ShippingChildFresh',
       'open Tools.ShippingChildCacheA Tools.ShippingChildRunAKids Tools.ShippingChildInv Sparkle.IR.AST Sparkle.IR.Machine',
       'open Sparkle.Compiler.Elab Tools.ShippingChildBndCore Tools.ShippingChildVCA', 'open Tools.ShippingSrm3Callee Tools.ShippingSrm4Kid Tools.ShippingSrm4Core6 Tools.ShippingSrm4Parent',
       'open Sparkle.Compiler.MachMemory (memModule)', 'open Sparkle.IR.OptCheck (checkedOptimize)', 'open Sparkle.IR.RefineCheck (mergeChecked)', 'open Tools.ShippingMachineLinked (childMap)',
       'open Tests.Compiler.SharedLeafMemKidTest Tests.Compiler.SharedLeafMemKidRunTest Tests.Compiler.SharedLeafMemKidEntryTest',
       'open Tools.ShippingSrm5Height Tools.ShippingSrm6Sem Tools.ShippingSrm11Bounds', 'open Tools.ShippingHierStateG (KT KSn KState runModuleTG)', 'open Sparkle.IR.RegDedup (declWidth)',
       'open Tools.ShippingDesignSV (envAt)', 'open Tools.ShippingDesignSVBounds (InvN)', 'open Sparkle.IR.Semantics (Bounded)', 'open Tools.ShippingSrm13Supply', 'open Tools.ShippingSeqOptSoundness (seedIn)', '',
       'variable {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State}', '']
for inst in ['topshareM', 'topshareQ']:
    for kind in ['svBoundsH', 'designSVH']:
        gs, concl = groups(sig_of(f'{inst}_{kind}_viaResetState'))
        b = [g for g in gs if bname(g) not in DELETE]
        out.append(build(f'Exp_{inst}_{kind}_viaResetSrc', b, concl))
        # a deliberately wrong expected form (mutation): the `hfit` binder deleted too
        if kind == 'svBoundsH' and inst == 'topshareM':
            out.append(build('Exp_mutation_noHfit', [g for g in b if bname(g) != 'hfit'], concl))
        if kind == 'svBoundsH':
            up = []
            for g in gs:
                up.append(g)
                if bname(g) == HO_UP_TO: break
            for r in DELETE:
                rg = [g for g in gs if bname(g) == r][0]
                ty = re.match(r'\(' + r + r' : (.*)\)$', rg, re.S).group(1)
                out.append(build(f'Exp_{inst}_{r}', up, ty))
out.append('end Tests.Compiler.Srm17ExpStmt')
open('Tests/Compiler/Srm17ExpStmt.lean', 'w').write('\n'.join(out) + '\n')
