#!/usr/bin/env python3
# Machine-generated COMPOSITION TABLE for SRM19 (writes scripts/srm19/COMPOSITION.txt).  Reads ONLY component SOURCE files:
#   SRM18 Tests/Compiler/Srm18ParentTest.lean  (topshare{M,Q}_svBoundsH_viaStartNk)
#   SRM14 Tests/Compiler/Srm14RankTest.lean    (topshare{M,Q}_svBoundsH_computed)
#   SRM16 Tests/Compiler/Srm16ParentTest.lean  (topshare{M,Q}_hO, _svBoundsH_viaResetO)
# Rule: the final theorem's binders = viaStartNk's binders with the 6 RANK binders (rk hrkmem + 4 own-rank equations) deleted; rk := rkOf gM 4 / rkOf gQ 3.
import re
def groups(sig):
    out=[];i=0;n=len(sig)
    while i<n:
        c=sig[i]
        if c in '({[':
            d=0;j=i
            while True:
                if sig[j] in '({[': d+=1
                elif sig[j] in ')}]': d-=1
                if d==0: break
                j+=1
            out.append(sig[i:j+1]);i=j+1
        elif c==':' and sig[i+1]!='=': return out,sig[i+1:].strip()
        else: i+=1
def names(g):
    m=re.match(r"[({\[]\s*([^:]+?)\s*:",g); return m.group(1).split() if m else []
def sig_of(f,name):
    s=open(f).read(); m=re.search(r'^theorem '+name+r'\b(.*?) :=',s,re.S|re.M); return m.group(1)
def lineno(f,name):
    for i,l in enumerate(open(f),1):
        if l.startswith('theorem '+name+' ') or l.startswith('theorem '+name+'\n'): return i
out=['SRM19 COMPOSITION TABLE (generated by scripts/srm19/gen_composition.py from component sources)']
RANK={'rk','hrkmem','hrT','hrW','hrW3','hrL','hrP','hrQ'}
for inst,N in [('M',2),('Q',1)]:
    f18='Tests/Compiler/Srm18ParentTest.lean'; f14='Tests/Compiler/Srm14RankTest.lean'; f16='Tests/Compiler/Srm16ParentTest.lean'
    v=f'topshare{inst}_svBoundsH_viaStartNk'; c=f'topshare{inst}_svBoundsH_computed'; o=f'topshare{inst}_svBoundsH_viaResetO'; h=f'topshare{inst}_hO'
    out.append(f'== instance topshare{inst} (depth {N}) ==')
    out.append(f'component viaStartNk {f18}:{lineno(f18,v)}; computed {f14}:{lineno(f14,c)}; viaResetO {f16}:{lineno(f16,o)}; hO {f16}:{lineno(f16,h)}')
    gv,cv=groups(sig_of(f18,v)); gc,cc=groups(sig_of(f14,c)); go,co=groups(sig_of(f16,o)); gh,ch=groups(sig_of(f16,h))
    nv=[n for g in gv for n in names(g)]; nc=[n for g in gc for n in names(g)]; no=[n for g in go for n in names(g)]; nh=[n for g in gh for n in names(g)]
    out.append('-- final theorem binders (viaStartNk minus rank binders), with supplier:')
    for n in nv:
        if n in RANK: continue
        s=[]
        if n in nh: s.append('hO binder (same term)')
        if n in no or (n in('st0','mems','kids') and 's' in no): s.append('viaResetO binder (same term'+(', s := ⟨st0,mems,kids⟩' if n in ('st0','mems','kids') else '')+')')
        if n in nc: s.append('SRM14 computed binder (same name)')
        if n=='hRK': s=['viaResetO hrk (same term); REPLACES hsk of SRM17; PREMISE ResetNk']
        out.append(f'  {n}: component viaStartNk; passed to ' + ('; '.join(s) if s else 'viaResetO'))
    out.append('-- rank binders deleted from the final theorem, filled inside the proof:')
    for n in nv:
        if n in RANK:
            out.append(f'  {n}: in viaStartNk (type: {[g for g in gv if n in names(g)][0][:100]}); final: rk := rkOf g, proof = SRM7 rkOf_mem / rkOf_decl+g*_ (same as SRM14 computed proof)')
    out.append('-- SRM14 computed binders that do NOT occur in viaStartNk (shape mismatch => SRM14 theorem itself not composable):')
    out.append('  ' + ', '.join(n for n in nc if n not in nv))
    out.append('-- viaStartNk binders absent from SRM14 computed: ' + ', '.join(n for n in nv if n not in nc))
open('scripts/srm19/COMPOSITION.txt','w').write('\n'.join(out)+'\n')
