#!/usr/bin/env python3
# Generates Tests/Compiler/Srm19ExpStmt.lean: EXPECTED full statements of the SRM19 end-to-end theorems, derived ONLY from component SOURCE statements:
#   SOURCE A: Tests/Compiler/Srm18ParentTest.lean  topshare{M,Q}_svBoundsH_viaStartNk   (signature text)
#   SOURCE B: Tests/Compiler/Srm14RankTest.lean    topshare{M,Q}_svBoundsH_computed      (supplies the rank-table term in its conclusion)
# Substitution/deletion list (printed): D1 delete binders rk hrkmem hrT hrW|hrP hrW3|hrQ hrL of A; S1 replace `rk` in A's conclusion by the term `(rkOf g n)` read from B's conclusion.
# Never reads the SRM19 theorems.  Also emits Exp_mutation_noHfit (hfit deleted) and Exp_mutation_rkVar (rank binders deleted but rk NOT substituted -> must be rejected).
import re
print('D1: delete binders rk hrkmem hrT hrW hrP hrW3 hrQ hrL of SOURCE A; S1: rk := rkOf-term of SOURCE B conclusion')
def groups(sig):
    out=[];i=0;n=len(sig)
    while i<n:
        c=sig[i]
        if c in '({[':
            d=0;j=i
            while True:
                if sig[j] in '({[': d+=1
                elif sig[j] in ')}]': d-=1
                if d==0: break
                j+=1
            out.append(sig[i:j+1]);i=j+1
        elif c==':' and sig[i+1]!='=': return out,sig[i+1:].strip()
        else: i+=1
def bname(g):
    m=re.match(r"[({\[]\s*([^\s:]+)",g); return m.group(1) if m else None
def sig_of(f,name):
    s=open(f).read(); m=re.search(r'^theorem '+name+r'\b(.*?) :=',s,re.S|re.M); return m.group(1)
DEL={'rk','hrkmem','hrT','hrW','hrP','hrW3','hrQ','hrL'}
VARS='∀ {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State},'
def build(name,gs,concl): return f"def {name} : Prop :=\n  {VARS}\n  ∀ {' '.join(gs)},\n    {concl}\n"
hdr=open('Tests/Compiler/Srm18ExpStmt.lean').read()  # reuse the open-list of the SRM18 generated file's header
opens=[l for l in hdr.split('\n') if l.startswith('open ') or l.startswith('variable')]
out=['import Tests.Compiler.Srm19EndToEndTest','-- GENERATED by scripts/srm19/gen_exp.py from the SRM18 viaStartNk and SRM14 computed SOURCE statements; do not edit by hand.',
     'set_option autoImplicit false','namespace Tests.Compiler.Srm19ExpStmt']+opens+['open Tools.ShippingSrm7Rank Tests.Compiler.Srm7RankTest','']
for inst in ['M','Q']:
    gs,concl=groups(sig_of('Tests/Compiler/Srm18ParentTest.lean',f'topshare{inst}_svBoundsH_viaStartNk'))
    _,cconcl=groups(sig_of('Tests/Compiler/Srm14RankTest.lean',f'topshare{inst}_svBoundsH_computed'))
    m=re.search(r'SVBoundsH \(childMap D\.modules\) (\(rkOf [^)]*\))',cconcl); rkt=m.group(1)
    new=[g for g in gs if bname(g) not in DEL]
    c2=concl.replace('(childMap D.modules) rk ','(childMap D.modules) '+rkt+' ',1)
    assert c2!=concl
    out.append(build(f'Exp_topshare{inst}_svBoundsH_endToEnd',new,c2))
    if inst=='M':
        out.append(build('Exp_mutation_noHfit',[g for g in new if bname(g)!='hfit'],c2))
        out.append(build('Exp_mutation_rkVar',[g for g in gs if bname(g) in ('rk',)]+new,concl))
out.append('end Tests.Compiler.Srm19ExpStmt')
open('Tests/Compiler/Srm19ExpStmt.lean','w').write('\n'.join(out)+'\n')
