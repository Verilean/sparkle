#!/usr/bin/env python3
"""Generate controls/U1MemPackedControls.lean from the harness's own probe text (MEASUREMENT ONLY).

    python3 scripts/ved/controls/gen_u1mem_controls.py scripts/ved/controls/U1MemPackedControls.lean
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import u1_gen  # noqa: E402

HEAD = '''/-
U1 measurement controls for the route `u1_mem_packed` and its probe (MEASUREMENT ONLY, never for main).

Run (after `kjob lake build Tools.VedWriteChecked Tools.VedMemEntry Tools.VedStrictAudit Sparkle`):
  timeout 900 python3 -I scratch/rss_guard.py 10485760 kjob lake env lean scripts/ved/controls/U1MemPackedControls.lean
The file elaborates without error iff every control holds; each prints `VED U1CTL <id> PASS`.
It is generated by scripts/ved/controls/gen_u1mem_controls.py: the probe below is MEM_PROBE_DEF of
scripts/ved/u1_gen.py, verbatim (a Python test checks that); the controls run THAT probe.

  M0  a memory-in-a-loop declaration with a product result through `#ved_write_checked mem_packed`: the
      probe ACCEPTS: THM theorem, TYPE exact (`MemPackedStmt` rebuilt), SLICES equal, PORT match,
      CONTRACT bound-to-mod, axioms std3, WRITTEN sv=equal cpp=equal;
  M1  the written .sv differs / the written _cppsim.h differs / a file is missing: WRITTEN rejects;
  M2  the files of ANOTHER declaration at the paths (check A, write B): WRITTEN differs;
  M3  a must-stay-refused memory row: a one-output memory declaration is refused at [packed], and a
      declaration with registers but no `Signal.loop` at [shape]; no theorem, no constant, no file.
-/
import Sparkle
import Sparkle.Compiler.Elab
import Tools.VedWriteChecked
import Tools.VedMemEntry
import Tools.VedStrictAudit

open Sparkle.Core.Domain Sparkle.Core.Signal Sparkle.Core.StateMacro

'''

TAIL = '''
open Lean Elab Command in
/-- Elaborate `#vedu1_mem_packed_probe n sv cpp`, drop its messages and require every pattern in `pats` to occur
in the probe's output (a pattern starting with `!` must NOT occur). -/
elab "#vedu1_mexpect " id:str n:ident sv:str cpp:str pats:str* : command => do
  let saved := (← get).messages
  modify fun s => { s with messages := MessageLog.empty }
  elabCommand (← `(command| #vedu1_mem_packed_probe $n $sv $cpp))
  let infos ← (← get).messages.toList.mapM fun m => m.data.toString
  modify fun s => { s with messages := saved }
  let all := "\\n".intercalate infos
  let has (p : String) := (all.splitOn p).length > 1
  for p in pats do
    let p := p.getString
    if p.startsWith "!" then
      let q := (p.drop 1).toString
      if has q then throwError m!"VED U1CTL {id.getString} FAIL: unexpected `{q}` in\\n{all}"
    else if !has p then throwError m!"VED U1CTL {id.getString} FAIL: missing `{p}` in\\n{all}"
  logInfo m!"VED U1CTL {id.getString} PASS"

open Lean Elab Command in
elab "#vedu1_absent " id:str n:ident : command => do
  if (← getEnv).contains n.getId then throwError m!"VED U1CTL {id.getString} FAIL: {n.getId} exists"
  logInfo m!"VED U1CTL {id.getString} absent {n.getId}"

open Lean Elab Command in
/-- the tool refuses (an error `VED U1 REFUSED <decl> [<stage>]`), leaving nothing behind -/
elab "#vedu1_refused " id:str stage:str c:command : command => do
  let saved := (← get).messages
  modify fun s => { s with messages := MessageLog.empty }
  elabCommand c
  let errs ← (← get).messages.toList.filterMapM fun m => do
    if m.severity == .error then pure (some (← m.data.toString)) else pure none
  modify fun s => { s with messages := saved }
  if errs.any (fun e => (e.splitOn s!"[{stage.getString}]").length > 1 && e.startsWith "VED U1 REFUSED") then
    logInfo m!"VED U1CTL {id.getString} refused at [{stage.getString}]"
  else throwError m!"VED U1CTL {id.getString} FAIL: no [{stage.getString}] refusal; errors: {errs}"

open Lean Elab Command in
/-- replace the file's text (`suffix` appended) or remove it (`none`) -/
elab "#vedu1_edit_file " p:str s:str : command => do
  let t ← IO.FS.readFile p.getString
  IO.FS.writeFile p.getString (t ++ s.getString)

open Lean Elab Command in
elab "#vedu1_rm_file " p:str : command => IO.FS.removeFile p.getString

declare_signal_state QState
  | idx  : BitVec 5  := 0#5
  | busy : Bool      := false
  | last : BitVec 16 := 0#16

set_option hygiene false in
macro "defMq " n:ident d:term : command => `(def $n {dom : DomainConfig} (start : Signal dom Bool) (writeEn : Signal dom Bool)
    (writeAddr : Signal dom (BitVec 4)) (writeData : Signal dom (BitVec 16)) :
    Signal dom (BitVec 16 × BitVec 5 × Bool) :=
  let state := Signal.loop fun state =>
    let idx := QState.idx state
    let busy := QState.busy state
    let readAddr4 := idx.map (BitVec.extractLsb' 0 4 ·)
    let inputCoeff := Signal.memoryComboRead writeAddr ($d) writeEn readAddr4
    let outMemRead := Signal.memory readAddr4 inputCoeff busy (Signal.pure 0#4)
    let done := busy &&& (idx === 15#5)
    let busyNext := Signal.mux done (Signal.pure false) (Signal.mux start (Signal.pure true) busy)
    let idxNext := Signal.mux busy (idx + 1#5) (Signal.pure 0#5)
    bundleAll! [Signal.register 0#5 idxNext, Signal.register false busyNext, Signal.register 0#16 outMemRead]
  bundle2 (QState.last state) (bundle2 (QState.idx state) (QState.busy state)))

namespace VedMc
defMq m0 writeData
defMq m1a writeData
defMq m1b writeData
defMq m1c writeData
defMq m2 writeData
defMq m2other (writeData + 1#16)

def one {dom : DomainConfig} (writeEn : Signal dom Bool) (writeAddr : Signal dom (BitVec 4))
    (writeData : Signal dom (BitVec 16)) (readAddr : Signal dom (BitVec 4)) : Signal dom (BitVec 16) :=
  Signal.memoryComboRead writeAddr writeData writeEn readAddr

def reg2 (a : Signal defaultDomain (BitVec 8)) : Signal defaultDomain (BitVec 8 × BitVec 8) :=
  bundle2 (Signal.register 0#8 a) a

/-! M0 -/
#writeDesign m0 ".lake/build/gen/u1memctl/m0.sv" ".lake/build/gen/u1memctl/m0_cppsim.h"
#ved_write_checked mem_packed m0 ".lake/build/gen/u1memctl/m0.sv" ".lake/build/gen/u1memctl/m0_cppsim.h"
#vedu1_mexpect "M0" m0 ".lake/build/gen/u1memctl/m0.sv" ".lake/build/gen/u1memctl/m0_cppsim.h" "THM theorem" "TYPE exact" "CONTRACT bound-to-mod" "MOD closed=true type=true" "SLICES expected=[(6,16),(1,5),(0,1)] stored=[(6,16),(1,5),(0,1)] equal" "WRITTEN sv=equal cpp=equal" "AXIOMS [Classical.choice, Quot.sound, propext]"

/-! M1: tampered / missing files -/
#ved_write_checked mem_packed m1a ".lake/build/gen/u1memctl/m1a.sv" ".lake/build/gen/u1memctl/m1a_cppsim.h"
#vedu1_edit_file ".lake/build/gen/u1memctl/m1a.sv" "// tampered\\n"
#vedu1_mexpect "M1a" m1a ".lake/build/gen/u1memctl/m1a.sv" ".lake/build/gen/u1memctl/m1a_cppsim.h" "THM theorem" "TYPE exact" "WRITTEN sv=differs cpp=equal"
#ved_write_checked mem_packed m1b ".lake/build/gen/u1memctl/m1b.sv" ".lake/build/gen/u1memctl/m1b_cppsim.h"
#vedu1_edit_file ".lake/build/gen/u1memctl/m1b_cppsim.h" "// tampered\\n"
#vedu1_mexpect "M1b" m1b ".lake/build/gen/u1memctl/m1b.sv" ".lake/build/gen/u1memctl/m1b_cppsim.h" "WRITTEN sv=equal cpp=differs"
#ved_write_checked mem_packed m1c ".lake/build/gen/u1memctl/m1c.sv" ".lake/build/gen/u1memctl/m1c_cppsim.h"
#vedu1_rm_file ".lake/build/gen/u1memctl/m1c.sv"
#vedu1_mexpect "M1c" m1c ".lake/build/gen/u1memctl/m1c.sv" ".lake/build/gen/u1memctl/m1c_cppsim.h" "WRITTEN sv=missing cpp=equal"

/-! M2: the files of another declaration -/
#ved_write_checked mem_packed m2 ".lake/build/gen/u1memctl/m2.sv" ".lake/build/gen/u1memctl/m2_cppsim.h"
#writeDesign m2other ".lake/build/gen/u1memctl/m2.sv" ".lake/build/gen/u1memctl/m2_cppsim.h"
#vedu1_mexpect "M2" m2 ".lake/build/gen/u1memctl/m2.sv" ".lake/build/gen/u1memctl/m2_cppsim.h" "THM theorem" "WRITTEN sv=differs cpp=differs"

/-! M3: refused rows leave nothing -/
#vedu1_refused "M3a" "packed" #ved_write_checked mem_packed one ".lake/build/gen/u1memctl/one.sv" ".lake/build/gen/u1memctl/one_cppsim.h"
#vedu1_absent "M3a" VedMc.one.ved_mem
#vedu1_absent "M3a" VedMc.one.ved_mod
#vedu1_mexpect "M3a" one ".lake/build/gen/u1memctl/one.sv" ".lake/build/gen/u1memctl/one_cppsim.h" "THM absent" "MOD absent" "WRITTEN sv=missing cpp=missing"
#vedu1_refused "M3b" "shape" #ved_write_checked mem_packed reg2 ".lake/build/gen/u1memctl/reg2.sv" ".lake/build/gen/u1memctl/reg2_cppsim.h"
#vedu1_absent "M3b" VedMc.reg2.ved_mem
#vedu1_mexpect "M3b" reg2 ".lake/build/gen/u1memctl/reg2.sv" ".lake/build/gen/u1memctl/reg2_cppsim.h" "THM absent" "WRITTEN sv=missing cpp=missing"
end VedMc
'''

def main():
    out = sys.argv[1]
    with open(out, "w") as f:
        f.write(HEAD + u1_gen.MEM_PROBE_DEF + "\n" + TAIL)

if __name__ == "__main__":
    main()
