#!/usr/bin/env python3
# Generates Tests/Compiler/Srm16ExpStmt.lean: the EXPECTED statements of the SRM16 corollaries / hO suppliers, derived ONLY from the SRM13 `_viaReset` SOURCE statements
# (Tests/Compiler/Srm13ParentTest.lean) by the explicit lists below.  Never reads SRM16 Lean sources or the theorems under audit.
import re
DELETE_O = ['hO']                       # corollaries A: this binder deleted
DELETE_B = ['hO', 'hrk']                # corollaries B: these binders deleted ...
INSERT_B = {'hrk': [                    # ... and, at hrk's position, these inserted ("{N}" = the depth of the source's hrk)
    '(hsk : s.kids = Tools.ShippingSrm16Reset.resetKids D {N} raw)',
    '(hIUraw : ∀ (mn i : String) (c : List (String × Sparkle.IR.AST.Expr)) (mn\' : String) (c\' : List (String × Sparkle.IR.AST.Expr)),\n      Stmt.inst mn i c ∈ raw.body → Stmt.inst mn\' i c\' ∈ raw.body → mn = mn\')',
    '(hIU : ∀ m ∈ D.modules, ∀ (mn i : String) (c : List (String × Sparkle.IR.AST.Expr)) (mn\' : String) (c\' : List (String × Sparkle.IR.AST.Expr)),\n      Stmt.inst mn i c ∈ m.body → Stmt.inst mn\' i c\' ∈ m.body → mn = mn\')',
    '(hAg : ∀ m ∈ D.modules, ∀ r c rs inp (init : Int) c\' rs\' inp\' (init\' : Int),\n      Stmt.register r c rs inp init ∈ m.body → Stmt.register r c\' rs\' inp\' init\' ∈ m.body → init.toNat = init\'.toNat)',
    '(hRd : ∀ m ∈ D.modules, ∀ nm aw dw c wa wd we ra rd cr ew er,\n      Stmt.memory nm aw dw c wa wd we ra rd cr ew er ∈ m.body →\n      ∀ c\' rs\' inp\' (init\' : Int), Stmt.register rd c\' rs\' inp\' init\' ∈ m.body → init\'.toNat = 0)']}
HO_UP_TO = 'hw'                         # hO suppliers: the binders of the source up to and including hw; conclusion = the type of the source's hO binder
print('A: delete', DELETE_O, '; B: delete', DELETE_B, 'insert at hrk:', [x.split()[0] for x in INSERT_B['hrk']], '; hO supplier: binders up to', HO_UP_TO, ', conclusion = hO type')

def groups(sig):
    out = []; i = 0; n = len(sig)
    while i < n:
        c = sig[i]
        if c in '({[':
            depth = 0; j = i
            while True:
                if sig[j] in '({[': depth += 1
                elif sig[j] in ')}]': depth -= 1
                if depth == 0: break
                j += 1
            out.append(sig[i:j + 1]); i = j + 1
        elif c == ':' and sig[i + 1] != '=':
            return out, sig[i + 1:].strip()
        else: i += 1
    raise SystemExit('no colon')
def bname(g):
    m = re.match(r'[({\[]\s*([^\s:]+)', g); return m.group(1) if m else None
src = open('Tests/Compiler/Srm13ParentTest.lean').read()
def sig_of(name):
    m = re.search(r'^theorem ' + name + r'\b(.*?) :=', src, re.S | re.M); return m.group(1)
VARS = '∀ {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State},'
def build(name, gs, concl):
    return f"def {name} : Prop :=\n  {VARS}\n  ∀ {' '.join(gs)},\n    {concl}\n"
out = ['import Tests.Compiler.Srm13ParentTest', 'import Tools.ShippingSrm16Reset', '-- GENERATED by scripts/srm16/gen_exp.py from the SRM13 source statements; do not edit by hand.',
       'set_option autoImplicit false', 'namespace Tests.Compiler.Srm16ExpStmt', 'open Lean Meta',
       'open Tools.ShippingEntrySoundness Tools.ShippingMachineEntry Tools.ShippingChildInvA Tools.ShippingChildFresh',
       'open Tools.ShippingChildCacheA Tools.ShippingChildRunAKids Tools.ShippingChildInv Sparkle.IR.AST Sparkle.IR.Machine',
       'open Sparkle.Compiler.Elab Tools.ShippingChildBndCore Tools.ShippingChildVCA', 'open Tools.ShippingSrm3Callee Tools.ShippingSrm4Kid Tools.ShippingSrm4Core6 Tools.ShippingSrm4Parent',
       'open Sparkle.Compiler.MachMemory (memModule)', 'open Sparkle.IR.OptCheck (checkedOptimize)', 'open Sparkle.IR.RefineCheck (mergeChecked)', 'open Tools.ShippingMachineLinked (childMap)',
       'open Tests.Compiler.SharedLeafMemKidTest Tests.Compiler.SharedLeafMemKidRunTest Tests.Compiler.SharedLeafMemKidEntryTest',
       'open Tools.ShippingSrm5Height Tools.ShippingSrm6Sem Tools.ShippingSrm11Bounds', 'open Tools.ShippingHierStateG (KT KSn KState runModuleTG)', 'open Sparkle.IR.RegDedup (declWidth)',
       'open Tools.ShippingDesignSV (envAt)', 'open Tools.ShippingDesignSVBounds (InvN)', 'open Sparkle.IR.Semantics (Bounded)', 'open Tools.ShippingSrm13Supply', 'open Tools.ShippingSeqOptSoundness (seedIn)', '',
       'variable {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State}', '']
for inst in ['topshareM', 'topshareQ']:
    for kind in ['svBoundsH', 'designSVH']:
        gs, concl = groups(sig_of(f'{inst}_{kind}_viaReset'))
        hrk = [g for g in gs if bname(g) == 'hrk'][0]
        N = re.search(r'ResetNk (\d)', hrk).group(1)
        a = [g for g in gs if bname(g) not in DELETE_O]
        b = []
        for g in gs:
            n = bname(g)
            if n in INSERT_B: b += [x.replace('{N}', N) for x in INSERT_B[n]]
            if n in DELETE_B: continue
            b.append(g)
        out.append(build(f'Exp_{inst}_{kind}_viaResetO', a, concl))
        out.append(build(f'Exp_{inst}_{kind}_viaResetState', b, concl))
        # a deliberately wrong expected form (mutation): the `hfit` binder deleted
        if kind == 'svBoundsH' and inst == 'topshareM':
            out.append(build('Exp_mutation_noHfit', [g for g in a if bname(g) != 'hfit'], concl))
    gs, concl = groups(sig_of(f'{inst}_svBoundsH_viaReset'))
    ho = [g for g in gs if bname(g) == 'hO'][0]
    hoty = re.match(r'\(hO : (.*)\)$', ho, re.S).group(1)
    up = []
    for g in gs:
        up.append(g)
        if bname(g) == HO_UP_TO: break
    out.append(build(f'Exp_{inst}_hO', up, hoty))
out.append('end Tests.Compiler.Srm16ExpStmt')
open('Tests/Compiler/Srm16ExpStmt.lean', 'w').write('\n'.join(out) + '\n')
