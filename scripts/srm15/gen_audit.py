#!/usr/bin/env python3
# SRM15: regenerate Tests/Compiler/Srm15AuditExpected.lean and scripts/srm15/PREMISES.txt from the S15PREM/S15DATA lines of a build log of Tests.Compiler.Srm15AuditTest.
# usage (from the repo root):  ./.cluster/qbuild.sh build Tests.Compiler.Srm15AuditTest > LOG 2>&1;  python3 scripts/srm15/gen_audit.py LOG
# (a stale expected file makes the first build fail AFTER printing the rows, so LOG always contains them.)
import re,sys,json
log=open(sys.argv[1]).read().split('\n')
rows=[]   # (thm,i,bi,name,isProp,type)
lines=[]
thms=[]
for l in log:
    m=re.search(r'(S15(?:PREM|DATA|THM)\|.*)$',l)
    if not m: continue
    line=m.group(1)
    if line.startswith('S15THM|'):
        thms.append(line.split('|')[1]); lines.append(line); continue
    tag,thm,i,bi,name,ty=line.split('|',5)
    rows.append((thm,int(i),bi,name,tag=='S15PREM',ty))
    lines.append(line)
open('scripts/srm15/PREMISES.txt','w').write('\n'.join(lines)+'\n')
order=list(thms)
by={t:[] for t in thms}
for r in rows:
    by[r[0]].append(r)
def lit(s): return json.dumps(s,ensure_ascii=False)
out=['import Lean','-- GENERATED by scripts/srm15/gen_audit.py from the S15PREM/S15DATA lines of a build of Tests.Compiler.Srm15AuditTest; do not edit by hand.',
     'namespace Tests.Compiler.Srm15AuditExpected','open Lean','',
     '/-- the expected premise table: per audited theorem, every binder `(index, binderInfo, name, isProp, type)` -/',
     'def expectedRows : List (Name × List (Nat × String × String × Bool × String)) :=']
items=[]
for t in order:
    rs=',\n    '.join('(%d, %s, %s, %s, %s)'%(r[1],lit(r[2]),lit(r[3]),'true' if r[4] else 'false',lit(r[5])) for r in by[t])
    items.append('  (`%s, [%s])'%(t,('\n    '+rs) if rs else ''))
out.append('  ['+',\n  '.join(x.lstrip() for x in items)+']')
out.append('')
out.append('end Tests.Compiler.Srm15AuditExpected')
open('Tests/Compiler/Srm15AuditExpected.lean','w').write('\n'.join(out)+'\n')
print(len(rows),'binders',len(order),'theorems')
