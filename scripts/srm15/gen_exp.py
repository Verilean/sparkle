#!/usr/bin/env python3
# Generates Tests/Compiler/Srm15ExpStmt.lean: the EXPECTED statements of the SRM15 theorems, derived ONLY from the SRM12 SOURCE statements
# (Tools/ShippingSrm12Corr.lean `ran_designCorr`, Tests/Compiler/Srm12CorrTest.lean `topshareM_corr`/`topshareQ_corr`) by the explicit lists below.  Never reads SRM15 Lean sources.
import re
SUBST_G = 'graphOf ds'                       # g := graphOf ds in every remaining binder and in the conclusion
REPLACE_BINDER = {'g': '(ds : List (Name × MachineData))'}         # binder g replaced by ds
DELETE_BINDER = ['hgraph']                                          # binder deleted (replaced by hfirst below)
INSERT_AFTER = {'d': '(hfirst : FirstOcc ds c d)'}                  # binder inserted after d
HIFACE = ('(hiface : ∀ (k : Nat) (hk : k < d.shape.insts.length) (y : Res), (originAt d.shape k).child? = none →\n'
          '      RealChildA O (d.shape.insts[k]).1 y →\n'
          '      ∃ (nArgs : Nat) (outs names : List String), ChildIfaceP (ofDecl (d.shape.insts[k]).1) nArgs outs names y.1 y.2)')
REPLACE_BINDER['hname'] = HIFACE                                    # binder hname replaced by the per-kid ChildIfaceP fact
SUBST_GM = {'gM': 'graphOf dsM', 'gQ': 'graphOf dsQ'}               # instances: graph constants replaced
print('ran_designCorr: g := graphOf ds; binder g -> ds; deleted', DELETE_BINDER, '; hname -> hiface; inserted after d:', INSERT_AFTER)
print('instances:', SUBST_GM)

def groups(sig):
    """split a signature `binders : concl` into (list of top-level bracket groups, conclusion)"""
    out = []; i = 0; n = len(sig)
    while i < n:
        c = sig[i]
        if c in '({[':
            close = {'(': ')', '{': '}', '[': ']'}[c]; depth = 0; j = i
            while True:
                if sig[j] in '({[': depth += 1
                elif sig[j] in ')}]': depth -= 1
                if depth == 0: break
                j += 1
            out.append(sig[i:j + 1]); i = j + 1
        elif c == ':' and sig[i + 1] != '=':
            return out, sig[i + 1:].strip()
        else: i += 1
    raise SystemExit('no colon')

def sig_of(path, name):
    src = open(path).read()
    m = re.search(r'^theorem ' + name + r'\b(.*?) :=', src, re.S | re.M)
    s = m.group(1)
    return s

def bname(g):
    m = re.match(r'[({\[]\s*([^\s:]+)', g)
    return m.group(1) if m else None

out = ['import Tests.Compiler.Srm15GraphTest', '-- GENERATED by scripts/srm15/gen_exp.py from the SRM12 source statements; do not edit by hand.',
       'set_option autoImplicit false', 'namespace Tests.Compiler.Srm15ExpStmt',
       'open Lean Meta', 'open Tools.ShippingSrm7Rank Tools.ShippingSrm12Corr Tools.ShippingSrm15Graph Sparkle.Compiler.MachInstOrigin',
       'open Tests.Compiler.SharedLeafMemKidTest Tests.Compiler.Srm7RankTest Tests.Compiler.Srm12CorrTest Tests.Compiler.Srm15GraphTest',
       'open Tools.ShippingEntrySoundness Tools.ShippingMachineEntry Tools.ShippingUnifiedSource Tools.ShippingMixedSourceBridge Tools.ShippingChildInvA Tools.ShippingChildFresh',
       'open Tools.ShippingChildCacheA Tools.ShippingChildRunAKids Tools.ShippingChildInv Sparkle.IR.AST Sparkle.IR.Machine',
       'open Sparkle.Compiler.Elab Tools.ShippingMachineAuto Tools.ShippingChildVCA Tools.ShippingChildBndCore Tools.ShippingChildRunA',
       'open Tools.ShippingMachineClosesData Tools.ShippingMachineCloses Tools.ShippingMemCloses Tools.ShippingCallsMemA Tools.ShippingSrm3Iface Tools.ShippingSrm3Callee',
       'open Tools.ShippingInstTagged (originAt)', 'open Sparkle.IR.ModuleName (ofDecl)', 'open Sparkle.IR.OptCheck (checkedOptimize)', 'open Sparkle.IR.RefineCheck (mergeChecked)',
       'open Tests.Compiler.SharedLeafMemKidIfaceTest Tests.Compiler.SharedLeafMemKidRunTest Tests.Compiler.SharedLeafMemKidEntryTest', '']
VARS = '∀ {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State},'

def build(name, gs, concl, with_hkids=True):
    return f"def {name} : Prop :=\n  {VARS}\n  ∀ {' '.join(gs)},\n    {concl}\n"

# --- ran_designCorr -> Exp_ran_designCorr_of_graphOf
gs, concl = groups(sig_of('Tools/ShippingSrm12Corr.lean', 'ran_designCorr'))
new = []
for g in gs:
    n = bname(g)
    if n in DELETE_BINDER: print('delete binder', n); continue
    if n in REPLACE_BINDER: new.append(REPLACE_BINDER[n]); print('replace binder', n); 
    else: new.append(re.sub(r'\bg\b', SUBST_G.join('()'), g))
    if n in INSERT_AFTER: new.append(INSERT_AFTER[n]); print('insert after', n)
# the first group after (O ...) -- the section variables (mctx ...) are not binders of the source signature
concl = re.sub(r'\bg\b', '(' + SUBST_G + ')', concl)
# `{c : Name}` comes from `{c : Name}` in the source; ds placed where g was
out.append(build('Exp_ran_designCorr_of_graphOf', new, concl))
mut = [g for g in new if bname(g) != 'hkids']
out.append(build('Exp_mutation_noHkids', mut, concl))
# --- instances
for nm, key in [('topshareM_corr', 'gM'), ('topshareQ_corr', 'gQ')]:
    gs, concl = groups(sig_of('Tests/Compiler/Srm12CorrTest.lean', nm))
    concl = re.sub(r'\b' + key + r'\b', '(' + SUBST_GM[key] + ')', concl)
    out.append(build('Exp_' + nm + '15', gs, concl))
out.append('end Tests.Compiler.Srm15ExpStmt')
open('Tests/Compiler/Srm15ExpStmt.lean', 'w').write('\n'.join(out) + '\n')
