#!/usr/bin/env python3
# Generates Tests/Compiler/Srm20ExpStmt.lean: EXPECTED full statements of the SRM20 bridge theorems, derived ONLY from component SOURCE statements and the committed substitution list below:
#   SOURCE A: Tests/Compiler/Srm9ComposedTest.lean  topshare{M,Q}_hierC_at_free   (consumes the ComposedG statement `topshare*_composed_binder`; supplies binders, hypotheses and the run)
#   SOURCE B: Tests/Compiler/Srm19EndToEndTest.lean topshare{M,Q}_svBoundsH_endToEnd (supplies hin hst₁ hst₂ hst₃ hfit and the SVBoundsH conclusion)
#   SOURCE C: scripts/srm20/EXPECTED.txt (fixed before proving) supplies the text of `def QDepthLift`.
# Substitution/deletion list (printed): D1 delete binder `closes` of A; S1 rename envsO -> envs; S2 insert premises hin hst₁ hst₂ hst₃ hfit of B before A's `∃ envsO`;
# S3 wrap A's output-agreement `∀ j …` in parens and append `∧ SVBoundsH …` of B's conclusion with T' := T; Q only: S4 `KT 2`→`KT 1`, `ResetNk 2`→`ResetNk 1`, `KSn (childMap D.modules) 2`→`… 1` (SRM19's depth), premise `Exp_QDepthLift raw D b →` after the kidsMasked premise (the theorem has it as the last binder `hlift`; the two are defeq).
# Never reads the SRM20 theorems.  Also emits mutations (Exp_mutation_noHfit, Exp_mutation_noReset, Exp_mutation_noHlift) that must be REJECTED by the audit.
import re,sys
print('D1 S1 S2 S3 (Q: S4)')
def groups(sig):
    out=[];i=0;n=len(sig)
    while i<n:
        c=sig[i]
        if c in '({[':
            d=0;j=i
            while True:
                if sig[j] in '({[': d+=1
                elif sig[j] in ')}]': d-=1
                if d==0: break
                j+=1
            out.append(sig[i:j+1]);i=j+1
        elif c==':' and sig[i+1]!='=': return out,sig[i+1:].strip()
        else: i+=1
def bname(g):
    m=re.match(r"[({\[]\s*([^\s:]+)",g); return m.group(1) if m else None
def btype(g):
    m=re.match(r"^[({\[][^:]*?:(.*)[)}\]]$",g,re.S); return m.group(1).strip()
def sig_of(f,name):
    s=open(f).read(); m=re.search(r'^theorem '+name+r'\b(.*?) :=',s,re.S|re.M); return m.group(1)
VARS='∀'
hdr=[l for l in open('Tests/Compiler/Srm20BridgeTest.lean').read().split('\n') if l.startswith('open ')]
qd=open('scripts/srm20/EXPECTED.txt').read()
m=re.search(r'^def QDepthLift .*?(?=\n\n|\ntheorem)',qd,re.S|re.M); qdef=m.group(0).replace('def QDepthLift','def Exp_QDepthLift')
out=['import Tests.Compiler.Srm20BridgeTest','-- GENERATED by scripts/srm20/gen_exp.py from the SRM9 hierC_at_free and SRM19 endToEnd SOURCE statements and scripts/srm20/EXPECTED.txt; do not edit by hand.',
     'set_option autoImplicit false','namespace Tests.Compiler.Srm20ExpStmt']+hdr+['open Tests.Compiler.Srm9ComposedTest','open Tools.ShippingMixedSourceBridge (SourceInputs)','']
out.append(qdef); out.append('')
def build(name,gs,concl): return f"def {name} : Prop :=\n  ∀ {' '.join(gs)},\n    {concl}\n"
for inst in ['M','Q']:
    gsA,cA=groups(sig_of('Tests/Compiler/Srm9ComposedTest.lean',f'topshare{inst}_hierC_at_free'))
    gsB,cB=groups(sig_of('Tests/Compiler/Srm19EndToEndTest.lean',f'topshare{inst}_svBoundsH_endToEnd'))
    byB={bname(g):btype(g) for g in gsB}
    prem=[byB[k] for k in ['hin','hst₁','hst₂','hst₃','hfit']]
    new=[g for g in gsA if bname(g)!='closes']; assert len(new)==len(gsA)-1
    i=cA.index('∃ envsO,'); P=cA[:i]; Tl=cA[i:]
    Tl=Tl.replace('envsO','envs')
    mm=re.search(r'∧\s*∀ j \(hj',Tl); j=mm.start(); Tl=Tl[:j]+'∧ (∀ j (hj'+Tl[mm.end():]+')'
    m=re.search(r'SVBoundsH .*',cB); sv=m.group(0).replace("T'","T")
    Tl=Tl+' ∧\n      '+sv
    cat=P
    nores=None
    if inst=='Q':
        for a,b2 in [('KT 2','KT 1'),('ResetNk 2','ResetNk 1'),('KSn (childMap D.modules) 2','KSn (childMap D.modules) 1')]:
            assert a in cat+Tl, a
            cat=cat.replace(a,b2); Tl=Tl.replace(a,b2)
    full=cat+'\n    '+' →\n    '.join('('+p+')' for p in prem)+' →\n    '+Tl
    gsN=new
    if inst=='Q':
        k=full.index('∃ ids'); fullQ=full[:k]+'(Exp_QDepthLift raw D b) →\n    '+full[k:]
    out.append(build(f'Exp_topshare{inst}_svBoundsH_underComposedG',gsN,fullQ if inst=='Q' else full))
    if inst=='M':
        fitp='('+prem[4]+') →\n    '
        assert fitp in full
        out.append(build('Exp_mutation_noHfit',gsN,full.replace(fitp,'',1)))
        assert 'ResetNk 2 raw D kids →' in full
        out.append(build('Exp_mutation_noReset',gsN,full.replace('ResetNk 2 raw D kids →','',1)))
    else:
        out.append(build('Exp_mutation_noHlift',new,full))
out.append('end Tests.Compiler.Srm20ExpStmt')
open('Tests/Compiler/Srm20ExpStmt.lean','w').write('\n'.join(out)+'\n')
