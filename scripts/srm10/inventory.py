#!/usr/bin/env python3
"""SRM10 O1: machine-generated inventory of every `outsCheck` occurrence (Tools/Sparkle/Tests/scripts *.lean).
Usage: python3 -I scripts/srm10/inventory.py > scripts/srm10/INVENTORY.txt
Each occurrence: file:line, enclosing declaration (last theorem/def header above), kind:
  DEF       the definition `def outsCheck`
  COMMENT   inside a `--` line / block comment
  STMT-HYP   occurrence in a declaration STATEMENT (before its `:=`) as a hypothesis (binder `(hoc : outsCheck ..)` or `outsCheck .. = true →`)
  STMT-CONCL occurrence in a declaration statement that is not a hypothesis (a conclusion / a definition body line)
  PROOF-USE  occurrence after the `:=` (a proof/definition body mentions it)
Then the hand classification of the CORE consumers (those that open outsCheck) is appended from CLASS below,
and the script FAILS if a core consumer name does not occur in the scan (so a rename fails loudly)."""
import re, sys, os, collections
ROOTS = ['Tools', 'Sparkle', 'Tests', 'scripts']
HDR = re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*(theorem|lemma|def|abbrev|instance|structure|inductive|opaque)\s+([^\s:({\[]+)')
occ = []
for root in ROOTS:
    for dp, _, fs in sorted(os.walk(root)):
        if '/.lake' in dp:
            continue
        for f in sorted(fs):
            if not f.endswith('.lean'):
                continue
            p = os.path.join(dp, f)
            cur = None
            incomment = 0
            instmt = False
            for i, l in enumerate(open(p, encoding='utf-8', errors='replace'), 1):
                s = l.rstrip('\n')
                m = HDR.match(s)
                if m:
                    cur = m.group(2)
                    instmt = True
                was_stmt = instmt
                if instmt and ':=' in s:
                    instmt = False
                started_in_comment = incomment > 0
                k = 0
                while True:
                    a = s.find('/-', k) if incomment == 0 else s.find('-/', k)
                    if a < 0:
                        break
                    incomment = 1 - incomment
                    k = a + 2
                if 'outsCheck' not in s:
                    continue
                st = s.strip()
                if started_in_comment or incomment > 0 or st.startswith('--') or st.startswith('/-'):
                    kind = 'COMMENT'
                elif re.match(r'^\s*def outsCheck\b', s):
                    kind = 'DEF'
                elif was_stmt and (re.search(r'\(\s*[\w\']+\s*:\s*(Tools\.ShippingDesignSVBack\.)?outsCheck', s) or re.search(r'outsCheck\b.*=\s*true\s*→', s)):
                    kind = 'STMT-HYP'
                elif was_stmt:
                    kind = 'STMT-CONCL'
                else:
                    kind = 'PROOF-USE'
                occ.append((p, i, cur or '-', kind, st[:110]))
by = collections.OrderedDict()
for o in occ:
    by.setdefault(o[3], []).append(o)
print('# SRM10 inventory of `outsCheck` occurrences (GENERATED by scripts/srm10/inventory.py; do not edit)')
print('total occurrences', len(occ), 'files', len({o[0] for o in occ}))
for k, v in sorted(by.items()):
    print('kind', k, len(v))
for o in occ:
    print('%s:%d\t%s\t%s\t%s' % o)
CLASS = [
 ('design_sv_backN', 'Tools/ShippingDesignSVBack.lean',
  'depth 0: kidsPass_at hoc gives outsLeaf child (leaf_outs); depth m+1: kidsPass_at hoc gives outsAssigned child AND outsCheck C m child (textRun_outs, then the induction hypothesis)',
  'induction on the UNIFORM depth n: a kid at remaining depth 0 needs outsLeaf, a kid at remaining depth >0 needs outsAssigned plus the same of its own kids',
  'needs uniform depth AS WRITTEN. The per-kid conjunct (outsLeaf for a rank-0 kid, outsAssigned for a kid of rank>0, recursively over its instances) is what a per-module height supplies (houtsMod). A height-indexed restatement of design_sv_backN itself is the SRM6 HeightBridge (owner SRM6), not done here'),
 ('design_sv_unique', 'Tools/ShippingDesignSVBack.lean', 'passes hoc twice to design_sv_backN', 'as design_sv_backN', 'needs uniform depth (inherited)'),
 ('design_sv_all', 'Tools/ShippingDesignSVBack.lean', 'passes hoc to design_sv_unique', 'as design_sv_backN', 'needs uniform depth (inherited); consumed through the hoc binder of design_at_free'),
 ('design_at_free', 'Tools/ShippingShipsFree.lean', 'binder hoc : Bnd raw D -> outsCheck (childMap D.modules) n (checkedOptimize b) = true, passed unopened to design_sv_all', 'uniform n (same n as designCheck)', 'needs uniform depth (inherited); SRM8 design_at_free_h keeps this binder'),
 ('ships_design_svN_all', 'Tools/ShippingShipsDesignSVAll.lean', 'hypothesis outsCheck .. n .. = true -> ..., passed to design_sv_all', 'uniform n', 'needs uniform depth (inherited)'),
 ('ships_design_svH_all', 'Tools/ShippingShipsDesignSVAll.lean', 'hypothesis outsCheck .. 0 .. = true -> ..., passed on', 'depth 0 only', 'needs uniform depth (depth 0; restatable trivially as houtsCheck for kids of rank 0)'),
 ('evalShipsHierH', 'Tools/ShippingPremiseEval.lean', 'computes the uniform Bool outsCheck as the report field uniqueCheck (decide)', 'uniform n', 'unclear (an evaluator, not a proof consumer; no soundness theorem uses it)'),
 ('textRun_outs', None, 'outsAssigned m (a single-module fact; does not mention outsCheck)', 'none', 'restatable per module'),
 ('leaf_outs', None, 'outsLeaf m (a single-module fact; does not mention outsCheck)', 'none', 'restatable per module'),
]
print('\n# HAND CLASSIFICATION of the core consumers')
names = {o[2] for o in occ}
bad = False
for d, f, conj, dep, cl in CLASS:
    ok = True if f is None else d in names
    print('CORE %s [%s] present_in_scan=%s' % (d, f, ok))
    print('  conjunct :', conj)
    print('  condition:', dep)
    print('  class    :', cl)
    bad = bad or not ok
if bad:
    print('MISSING core consumer', file=sys.stderr)
    sys.exit(1)
