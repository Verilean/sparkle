#!/usr/bin/env python3
# Generates Tests/Compiler/Srm31AuditExpected.lean: the EXPECTED statements (scripts/srm31/EXPECTED.txt) as `def Exp_* : Prop := ∀ binders, type`,
# extracted from the TEXT of the ORIGINAL theorems (Tools/ShippingShipsFree.lean, Tests/Compiler/Srm9ComposedTest.lean) with the replacement rules of EXPECTED.txt.
# Independent of Tools/ShippingSrm31Core.lean and Tests/Compiler/Srm31EndpointTest.lean.
import re,sys
def sig(path,name):
    s=open(path).read()
    i=s.index('theorem '+name+'\n') if ('theorem '+name+'\n') in s else s.index('theorem '+name+' ')
    j=i+len('theorem '+name)
    depth=0;k=j
    while True:
        c=s[k]
        if s.startswith('--',k):
            k=s.index('\n',k);continue
        if c in '({[': depth+=1
        elif c in ')}]': depth-=1
        elif c==':' and depth==0 and s[k+1]!='=': break
        k+=1
    binders=s[j:k]
    e=s.index('\n  Tools.ShippingShipsFree.machine_ships_hierC_at_free',k) if 'Srm9' in path else s.index(':= by',k)
    typ=s[k+1:e].rstrip()
    if typ.endswith(':='): typ=typ[:-2].rstrip()
    return binders.strip(),typ.strip()
def exp(name,binders,typ,pre=''):
    return f"def {name} : Prop :=\n  ∀ {binders},\n  {typ}\n"
HSTR='''(∀ r ∈ seqRegs (openFlat b (openIns b) (openOuts b)), st0 r.1 < 2 ^ declWidth b r.1) →'''
def hwd(N): return f'''(∀ (k : Nat) (r : String) (f : SlotField), regs[k]? = some r →
              topshare{N}.machineData.shape.layout.slots[k]? = some f → f.width ≤ declWidth b r) →'''
