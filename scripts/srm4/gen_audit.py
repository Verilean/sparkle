def sig(text,name):
    i=text.index('theorem '+name+' ')
    j=i+len('theorem '+name)
    # find ':=' at paren depth 0 that ends the signature: first ':= by' or ':=\n' at depth0
    depth=0; k=j; res_colon=None
    while k<len(text):
        c=text[k]
        if c in '([{⟨': depth+=1
        elif c in ')]}⟩': depth-=1
        elif c==':' and depth==0 and text[k+1:k+2]!='=' and res_colon is None: res_colon=k
        elif c==':' and text[k+1:k+2]=='=' and depth==0: break
        k+=1
    binders=text[j:res_colon].strip(); result=text[res_colon+1:k].strip()
    return binders,result
def prefix(binders,result):
    s=binders+' '+result
    out=[]
    for v,t in [('mctx','{mctx : Lean.Meta.Context}'),('mref','{mref : ST.Ref IO.RealWorld Lean.Meta.State}'),('cctx','{cctx : Lean.Core.Context}'),('cref','{cref : ST.Ref IO.RealWorld Lean.Core.State}')]:
        if re.search(r'(?<![\w\'])'+v+r'(?![\w\'])',s): out.append(t)
    return ' '.join(out)
