#!/usr/bin/env python3
# Generates Tests/Compiler/Srm18ExpStmt.lean: the EXPECTED statements of the SRM18 `_viaStartNk` corollaries and `_hsk_not_forced` theorems, derived ONLY from the SRM17 `_viaResetSrc` SOURCE statements
# (Tests/Compiler/Srm17ParentTest.lean) by the explicit lists below.  Never reads SRM18 Lean sources or the theorems under audit.
import re
print('corollary: S2 binder s -> (st0 mems kids); S3 binder hsk -> hRK : ResetNk N raw D kids (same position); S4 s.st->st0, s.kids->kids, other s -> <st0,mems,kids>; '
      'hsk_not_forced: binders ins T\' s envs hrun of the source (hrun kept verbatim) + conclusion written below, in {raw b D}')
def groups(sig):
    out = []; i = 0; n = len(sig)
    while i < n:
        c = sig[i]
        if c in '({[':
            depth = 0; j = i
            while True:
                if sig[j] in '({[': depth += 1
                elif sig[j] in ')}]': depth -= 1
                if depth == 0: break
                j += 1
            out.append(sig[i:j + 1]); i = j + 1
        elif c == ':' and sig[i + 1] != '=':
            return out, sig[i + 1:].strip()
        else: i += 1
    raise SystemExit('no colon')
def bname(g):
    m = re.match(r"[({\[]\s*([^\s:]+)", g); return m.group(1) if m else None
src = open('Tests/Compiler/Srm17ParentTest.lean').read()
def sig_of(name):
    m = re.search(r'^theorem ' + name + r'\b(.*?) :=', src, re.S | re.M); return m.group(1)
VARS = '∀ {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State},'
def build(name, gs, concl):
    return f"def {name} : Prop :=\n  {VARS}\n  ∀ {' '.join(gs)},\n    {concl}\n"
out = ['import Tests.Compiler.Srm18ParentTest', '-- GENERATED by scripts/srm18/gen_exp.py from the SRM17 source statements; do not edit by hand.',
       'set_option autoImplicit false', 'namespace Tests.Compiler.Srm18ExpStmt', 'open Lean Meta',
       'open Tools.ShippingEntrySoundness Tools.ShippingMachineEntry Tools.ShippingChildInvA Tools.ShippingChildFresh',
       'open Tools.ShippingChildCacheA Tools.ShippingChildRunAKids Tools.ShippingChildInv Sparkle.IR.AST Sparkle.IR.Machine',
       'open Sparkle.Compiler.Elab Tools.ShippingChildBndCore Tools.ShippingChildVCA', 'open Tools.ShippingSrm3Callee Tools.ShippingSrm4Kid Tools.ShippingSrm4Core6 Tools.ShippingSrm4Parent',
       'open Sparkle.Compiler.MachMemory (memModule)', 'open Sparkle.IR.OptCheck (checkedOptimize)', 'open Sparkle.IR.RefineCheck (mergeChecked)', 'open Tools.ShippingMachineLinked (childMap)',
       'open Tests.Compiler.SharedLeafMemKidTest Tests.Compiler.SharedLeafMemKidRunTest Tests.Compiler.SharedLeafMemKidEntryTest',
       'open Tools.ShippingSrm5Height Tools.ShippingSrm6Sem Tools.ShippingSrm11Bounds', 'open Tools.ShippingHierStateG (KT KSn KState runModuleTG)', 'open Sparkle.IR.RegDedup (declWidth)',
       'open Tools.ShippingDesignSV (envAt)', 'open Tools.ShippingDesignSVBounds (InvN)', 'open Sparkle.IR.Semantics (Bounded)', 'open Tools.ShippingSrm13Supply', 'open Tools.ShippingSeqOptSoundness (seedIn)', '',
       'variable {mctx : Lean.Meta.Context} {mref : ST.Ref IO.RealWorld Lean.Meta.State} {cctx : Lean.Core.Context} {cref : ST.Ref IO.RealWorld Lean.Core.State}', '']
for inst in ['topshareM', 'topshareQ']:
    N = 2 if inst == 'topshareM' else 1
    anon = '(⟨st0, mems, kids⟩ : KState (KT %d))' % N
    def sub(t):
        t = t.replace('s.st', 'st0').replace('s.kids', 'kids')
        return re.sub(r"(?<![\w'.])s(?![\w'.₀-₉])", anon, t)
    for kind in ['svBoundsH', 'designSVH']:
        gs, concl = groups(sig_of(f'{inst}_{kind}_viaResetSrc'))
        new = []
        for g in gs:
            nm = bname(g)
            if nm == 's': new.append('(st0 : String → Nat) (mems : Sparkle.IR.Semantics.MEnv) (kids : String → KT %d)' % N)
            elif nm == 'hsk': new.append('(hRK : Tools.ShippingMachineShipsDepth.ResetNk %d raw D kids)' % N)
            else: new.append(sub(g))
        out.append(build(f'Exp_{inst}_{kind}_viaStartNk', new, sub(concl)))
        if kind == 'svBoundsH' and inst == 'topshareM':
            out.append(build('Exp_mutation_noHfit', [g for g in new if bname(g) != 'hfit'], sub(concl)))
        if kind == 'svBoundsH':
            hrun = [g for g in gs if bname(g) == 'hrun'][0]
            sg = '(raw b : Sparkle.IR.AST.Module) (D : Sparkle.IR.AST.Design) (ins : Nat → String → Nat) (T\' : Nat) (s : KState (KT %d)) (envs : List Sparkle.IR.Semantics.Env) ' % N + hrun
            # the generated header prints raw b D as explicit binders; the audited theorems have them implicit: use implicit braces to match
            sg = sg.replace('(raw b : Sparkle.IR.AST.Module) (D : Sparkle.IR.AST.Design)', '{raw b : Sparkle.IR.AST.Module} {D : Sparkle.IR.AST.Design}')
            concl2 = ('∃ s\' : KState (KT %d), runModuleTG (KSn (childMap D.modules) %d) (declWidth (checkedOptimize b)) (childMap D.modules) (checkedOptimize b).body (seedIn b ins) T\' s\' = some envs ∧ '
                      's\'.st = s.st ∧ s\'.mems = s.mems ∧ s\'.kids ≠ Tools.ShippingSrm16Reset.resetKids D %d raw ∧ '
                      '(Tools.ShippingMachineShipsDepth.ResetNk %d raw D s.kids → Tools.ShippingMachineShipsDepth.ResetNk %d raw D s\'.kids)') % (N, N, N, N, N)
            out.append(f"def Exp_{inst}_hsk_not_forced : Prop :=\n  ∀ {sg},\n    {concl2}\n")
out.append('end Tests.Compiler.Srm18ExpStmt')
open('Tests/Compiler/Srm18ExpStmt.lean', 'w').write('\n'.join(out) + '\n')
