#!/usr/bin/env python3
# SRM8: render scripts/srm8/SUPPLY_TABLE.md from the S8SUPPLY lines of a build log of Tests.Compiler.Srm8AuditTest.
# usage: ./.cluster/qbuild.sh build Tests.Compiler.Srm8AuditTest > LOG 2>&1; python3 scripts/srm8/gen_table.py LOG
import re,sys
rows=[]
for l in open(sys.argv[1]).read().split('\n'):
    m=re.search(r'S8SUPPLY\|(.*)$',l)
    if m: rows.append(m.group(1).split('|',6))
out=['# SRM8 premise-supply table (GENERATED by scripts/srm8/gen_table.py from the S8SUPPLY lines; do not edit)','',
'Endpoint audited: `Tools.ShippingSrm8Bridge.design_at_free_h` (= `Tools.ShippingShipsFree.design_at_free` with `HeightPass` + `HeightBridge` in place of `designCheck`);',
'its `F` is the conclusion of `Tools.ShippingShipsFree.machine_ships_hierC_at_free`. Memory-free reference endpoints: `Tools.ShippingOneOutHead.machine_design_svH_free` (depth 0), `Tests.Compiler.ParentHoutTyTest.parent_noShips_noBdA_dcH` (depth n).',
'Status: PROVED-GENERIC / PROVED-INSTANCE (topshareM, topshareQ only) / PREMISE / MISSING. A classification checked for existence and standard axioms of the cited theorems, not a proof of satisfiability.','',
'| theorem | binder | status | suppliers | owner | binder type |','|---|---|---|---|---|---|']
for r in rows:
    t,b,s,sup,own,ty=r[0],r[1],r[2],r[3],r[4],r[5] if len(r)>5 else ''
    ty=ty.replace('|','\\|')
    out.append('| `%s` | `%s` | %s | %s | %s | `%s` |'%(t.split('.')[-1] if False else t,b,s,sup.replace(',','<br>'),own,ty[:160]))
open('scripts/srm8/SUPPLY_TABLE.md','w').write('\n'.join(out)+'\n')
print(len(rows),'rows')
