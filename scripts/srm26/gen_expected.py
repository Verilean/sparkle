#!/usr/bin/env python3
# Generates Tests/Compiler/Srm26AuditExpected.lean from scripts/srm26/EXPECTED.txt (committed before any proof file).
# Blocks 1-3 are taken VERBATIM from EXPECTED.txt (comment lines dropped, `theorem N binders : concl` -> `def Exp_N : Prop := ∀ binders, concl`,
# `SRA` -> `Exp_SRA`).  Block 4 (shippedRegsAreSlots_of_wired) is abbreviated in EXPECTED.txt ("same as above"): it is built here from block 3's binders by
# inserting `(hgate : hierGate m = true)` first and changing the conclusion, as EXPECTED.txt states.  Mutants are produced from block 3/4 text by explicit rules.
import re, sys
txt = open('scripts/srm26/EXPECTED.txt', encoding='utf8').read()
lines = [l for l in txt.split('\n') if not l.strip().startswith('--')]
blocks = []; cur = None
for l in lines:
    if l.startswith('theorem '):
        cur = [l]; blocks.append(cur)
    elif cur is not None:
        if l.strip() == '': cur = None
        else: cur.append(l)
def split(block):
    s = '\n'.join(block); s = s[len('theorem '):]
    name, rest = s.split(None, 1); depth = 0
    for i, ch in enumerate(rest):
        if ch in '([{': depth += 1
        elif ch in ')]}': depth -= 1
        elif ch == ':' and depth == 0 and rest[i+1:i+2] in (' ', '\n'):
            return name, rest[:i].strip(), rest[i+1:].strip()
    raise Exception('no colon ' + name)
b = {n: (bd, c) for n, bd, c in map(split, blocks[:3])}
assert list(b) == ['subset_of_length_le', 'sourceRegsAreSlots_regs_of_ports', 'sourceRegsAreSlots_of_wired'], list(b)
def fix(t): return re.sub(r'\bSRA\b', 'Exp_SRA', t)
def d(name, bd, c): return f'def Exp_{name} : Prop := ∀ {fix(bd)},\n    {fix(c)}\n'
out = []
out.append('''import Tools.ShippingSrm26Order
set_option autoImplicit false
-- GENERATED by scripts/srm26/gen_expected.py from scripts/srm26/EXPECTED.txt (committed before the proof file); independent of Tools/ShippingSrm26Order.lean.
namespace Tests.Compiler.Srm26AuditExpected
open Lean hiding Module Expr
open Sparkle.IR.AST Sparkle.IR.RefineCheck
open Sparkle.IR.Machine (SlotField)
open Sparkle.Compiler.Elab (MachineShape)
open Tools.ShippingMachineEntry (MachineWired machPorts)
open Tools.ShippingSrm22Width (ShippedRegsAreSlots)

def Exp_SRA (b : Module) (regs : List String) (slots : List SlotField) : Prop :=
  ∀ (r c : String) (rs : String × Sparkle.IR.Type.ResetKind) (inp : Expr) (init : Int),
    Stmt.register r c rs inp init ∈ b.body →
      ∃ (k : Nat) (f : SlotField), regs[k]? = some r ∧ slots[k]? = some f ∧ init = Int.ofNat f.init
''')
for n in b: out.append(d(n, *b[n]))
bd3, c3 = b['sourceRegsAreSlots_of_wired']
# block 4: hgate first, shipped conclusion
bd4 = bd3.replace('(hW :', '(hgate : hierGate m = true)\n    (hW :', 1)
out.append(d('shippedRegsAreSlots_of_wired', bd4, 'ShippedRegsAreSlots m regs shape.layout.slots'))
# aux lemma added during proving (NOT in EXPECTED.txt): stated here by hand
out.append('''-- AUX (added while proving; not frozen in EXPECTED.txt): positions of distinct entries
def Exp_nodup_getElem?_inj : Prop := ∀ {α : Type} (l : List α) (i j : Nat) (x : α), l.Nodup → l[i]? = some x → l[j]? = some x → i = j
''')
# mutants (must be rejected by the BINDER-TABLE comparator)
Mc = 'sourceRegsAreSlots_regs_of_ports'
bdc, cc = b[Mc]
out.append('-- MUTANTS')
out.append(d('mut_wrongConclusion', bdc, fix('SRA b psN slots')).replace('Exp_mut_wrongConclusion', 'Exp_mut_wrongConclusion'))
# semantic fixture 1: ` ∧ True` on the Prop binder hK0 (row invariants: same index/name/binderInfo/isProp)
out.append(d('mut_withTrue', bdc.replace('(hK0 : SRA b psN slots)', '(hK0 : SRA b psN slots ∧ True)'), cc))
# semantic fixture 2: added data binder
out.append(d('mut_addedBinder', bdc.replace('(hpsNd :', '(extra : Nat) (hpsNd :', 1), cc))
# semantic fixture 3: reordered binders
out.append(d('mut_reordered', bdc.replace('(psN regs : List String)', '(regs psN : List String)', 1), cc))
# K1-as-premise mutant: an equation regs = psN premise added (must not match: no K1 premise exists)
out.append(d('mut_k1Premise', bdc.replace('(hK0 :', '(hK1 : regs = psN) (hK0 :', 1), cc))
out.append('end Tests.Compiler.Srm26AuditExpected\n')
open('Tests/Compiler/Srm26AuditExpected.lean', 'w', encoding='utf8').write('\n'.join(out))
