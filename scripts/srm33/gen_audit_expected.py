#!/usr/bin/env python3
# Generates Tests/Compiler/Srm33AuditExpected.lean from the TEXT of the ORIGINAL theorems (Tools/ShippingShipsFree.lean, Tests/Compiler/Srm9ComposedTest.lean)
# + scripts/srm33/EXPECTED.txt rules.  Independent of Tools/ShippingSrm33Core.lean and Tests/Compiler/Srm33EndpointTest.lean.
import re
sig_src=open('scripts/srm31/gen_audit_expected.py').read()
exec(sig_src[sig_src.index('def sig('):sig_src.index('out=[]')])
HSTR='''(∀ r ∈ seqRegs (openFlat b (openIns b) (openOuts b)), st0 r.1 < 2 ^ declWidth b r.1) →'''
def hwd(N): return f'''(∀ (k : Nat) (r : String) (f : SlotField), regs[k]? = some r →
              topshare{N}.machineData.shape.layout.slots[k]? = some f → f.width ≤ declWidth b r) →'''
out=[]
s31=open('Tests/Compiler/Srm31AuditExpected.lean').read()
HDR=s31[:s31.index('-- BUILT')].replace('Srm31EndpointTest','Srm33EndpointTest')+'''-- UNBUILT (unit SRM33): see REPORT-SRM33.md.
-- GENERATED by scripts/srm33/gen_audit_expected.py from the TEXT of the original theorems + scripts/srm33/EXPECTED.txt; do not edit by hand.
'''+s31[s31.index('namespace'):s31.index('open Tests.Compiler.Srm9ComposedTest (TmBnd')].replace('Srm31AuditExpected','Srm33AuditExpected')+'open Tests.Compiler.Srm9ComposedTest (TmBnd TqBnd tmExt tmExtB tqExt tqExtB)\n'
b,t=sig('Tools/ShippingShipsFree.lean','machine_ships_hierC_at_free')
b=b.replace('{σ : Type} (KS : Design → KStep σ) (hloc : ∀ D, KSLocal (KS D))\n    (Reset : Sparkle.IR.AST.Module → Design → (String → σ) → Prop)\n    (Bnd : CtxBnd)','{n : Nat} (hloc : ∀ D : Design, KSLocal (KSn (childMap D.modules) n))\n    (Bnd : CtxBnd)')
b=b.replace('(Inv : Sparkle.IR.AST.Module → σ → Prop)','(Inv : Sparkle.IR.AST.Module → KT n → Prop)')
b=b.replace('(KS D) b.body Inv','(KSn (childMap D.modules) n) b.body Inv')
b=b.replace('ResetImpliesInv Reset Inv','ResetImpliesInv (ResetNk n) Inv')
old_c=b[b.index('    (composed :'):b.index('    (houtTy')]
new_c='''    (composed : ∀ {mctx : Meta.Context} {mref : ST.Ref IO.RealWorld Meta.State}
      {cctx : Core.Context} {cref : ST.Ref IO.RealWorld Core.State} {w w' : Void IO.RealWorld}
      {m : Sparkle.IR.AST.Module} {design : Design} {b : Sparkle.IR.AST.Module},
      RunsTo (synthesizeCombinationalCore declName [] false) mctx mref cctx cref w
        (m, design) w' →
      (b = Sparkle.IR.ZeroWidth.dropZeroWidthModule m ∨
        b = mergeChecked (Sparkle.IR.ZeroWidth.dropZeroWidthModule m)) →
      MachineDefines mctx mref cctx cref declName d.shape →
      C mctx mref cctx cref →
      Bnd mctx mref cctx cref w m design → Tools.ConeFold.memFree m.body →
      Tools.ShippingSrm28.ComposedNWRegs n declName d kD m design dom src ext extB
        (fun regs => ∀ (k : Nat) (r : String) (f : SlotField), regs[k]? = some r →
          d.shape.layout.slots[k]? = some f → f.width ≤ declWidth b r))
'''
b=b.replace(old_c,new_c)
b=b.replace('(houtTy : ∀ o ∈ d.shape.layout.outs, o.ty.bitWidth = o.width)','(houtTy : ∀ o ∈ d.shape.layout.outs, o.ty.bitWidth = o.width)\n    (hinitW : ∀ f ∈ d.shape.layout.slots, f.init < 2 ^ f.width)')
t=t.replace('(kids : String → σ)','(kids : String → KT n)').replace('Reset raw D kids →','ResetNk n raw D kids →').replace('runModuleTG (KS D)','runModuleTG (KSn (childMap D.modules) n)')
assert HSTR in t
tg=t.replace('\n            '+HSTR,'')
assert tg!=t
out.append(exp('Exp_generic',b,tg))
out.append(exp('Exp_generic_mut_hstrKept',b,t))
GH='''(∀ (k : Nat) (r : String) (f : SlotField), regs[k]? = some r →
              d.shape.layout.slots[k]? = some f → f.width ≤ declWidth b r) →'''
out.append(exp('Exp_generic_mut_hWdAdded',b,t.replace(HSTR,GH)))
for N in 'MQ':
    b,t=sig('Tests/Compiler/Srm9ComposedTest.lean','topshare%s_hierC_at_free'%N)
    assert HSTR in t
    out.append(exp('Exp_%s_orig'%N,b,t))
    new=t.replace('\n            '+HSTR,'')
    assert new!=t
    out.append(exp('Exp_%s'%N,b,new))
    out.append(exp('Exp_%s_mut_hstrKept'%N,b,t))
    out.append(exp('Exp_%s_mut_hWdAdded'%N,b,t.replace(HSTR,hwd(N))))
    wk=re.search(r'∀ j \(hj : j < envsO\.length\).*\Z',new,re.S); assert wk
    out.append(exp('Exp_%s_mut_weak'%N,b,new.replace(wk.group(0),'True')))
    hf='(∀ t x, x ∈ b.inputs.map (·.name) → ins t x < 2 ^ declWidth b x)'
    assert hf in new
    out.append(exp('Exp_%s_mut_withTrue'%N,b,new.replace(hf,'((∀ t x, x ∈ b.inputs.map (·.name) → ins t x < 2 ^ declWidth b x) ∧ True)')))
    out.append(exp('Exp_%s_mut_addedBinder'%N,b.replace('{b raw : Sparkle.IR.AST.Module}','(extra : Nat) {b raw : Sparkle.IR.AST.Module}'),new))
    h1='(∀ t, ins t "rst" = 0) → (∀ t st, seedIn b ins t st "clk" = 0) →'
    assert h1 in new
    out.append(exp('Exp_%s_mut_reordered'%N,b,new.replace(h1,'(∀ t st, seedIn b ins t st "clk" = 0) → (∀ t, ins t "rst" = 0) →')))
open('Tests/Compiler/Srm33AuditExpected.lean','w').write(HDR+'\n'.join(out)+'\nend Tests.Compiler.Srm33AuditExpected\n')
