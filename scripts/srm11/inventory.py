#!/usr/bin/env python3
"""SRM11 K1: machine-generated inventory.
Usage (repo root): python3 -I scripts/srm11/inventory.py > scripts/srm11/INVENTORY.txt
Part 1: exact source header (name .. binders .. conclusion, up to ':=' / the first '|' equation) of the SRM6/SRM11-relevant declarations, with file:line (found by scanning Tools/ and Tests/).
Part 2: the conjunct table of `SVBoundsH` per rank case and depth; each conjunct maps to a SUPPLIER (declaration located by the scan, file:line) or MISSING.
The script FAILS (nonzero exit) if a cited declaration is not found, so a rename or a missing supplier is loud."""
import re, os, sys
DECLS = ['svBounds_of_checks', 'design_sv_runH', 'SVBoundsH', 'SVBounds', 'LeafBounds', 'ParentBounds', 'InvN',
         'topshareM_designSVH', 'topshareQ_designSVH', 'topshareM_hcheck', 'topshareQ_hcheck',
         'svBoundsH_of_checks', 'svBoundsH_of_svBounds', 'runModuleTG_envBoundH', 'topshareM_svBoundsH', 'topshareQ_svBoundsH',
         'topshareM_designSVH_noB', 'topshareQ_designSVH_noB']
HDR = re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*(theorem|lemma|def|abbrev)\s+(\S+)')
found = {}
for root in ['Tools', 'Tests']:
    for dp, _, fs in sorted(os.walk(root)):
        if '/.lake' in dp: continue
        for f in sorted(fs):
            if not f.endswith('.lean'): continue
            p = os.path.join(dp, f)
            lines = open(p, encoding='utf-8', errors='replace').read().split('\n')
            for i, l in enumerate(lines):
                m = HDR.match(l)
                if m and m.group(2) in DECLS or (m and m.group(2).split('.')[-1] in DECLS):
                    nm = m.group(2).split('.')[-1]
                    hdr = []
                    for j in range(i, min(i + 60, len(lines))):
                        s = lines[j]
                        if j > i and re.match(r'^\s*\|', s): break
                        hdr.append(s.strip())
                        if ':=' in s and not s.strip().startswith('--'): break
                    found.setdefault(nm, []).append((p, i + 1, ' '.join(hdr)[:1400]))
def where(n):
    if n not in found:
        print('MISSING DECL', n, file=sys.stderr); sys.exit(1)
    return found[n]
print('# SRM11 K1 inventory (GENERATED by scripts/srm11/inventory.py; do not edit)')
print('## Part 1: exact headers')
for n in DECLS:
    for (p, ln, h) in where(n):
        print(f'{n}\t{p}:{ln}\t{h}')
print()
print('## Part 2: SVBoundsH conjuncts -> supplier')
SUP = lambda n: '%s:%d' % (where(n)[0][0], where(n)[0][1])
ROWS = [
 ('rank 0, any depth n', 'LeafBounds.1: seed maps bounded states to bounded envs', 'top: hseedB (premise of svBoundsH_of_checks); kid: connEnvS_bound + hpm (PortsMatch) + envAt_bound', 'svBoundsH_of_checks'),
 ('rank 0, any depth n', 'LeafBounds.2: Bounded (weS o) s.st', 'top: hst (premise); kid: InvN (premise hkids), unfolded', 'InvN'),
 ('rank h+1, any depth n', 'ParentBounds.1: oracle seeding bounded', 'oracle_bound + envAt_bound + runModuleTG_envBoundH (every cycle env bounded)', 'runModuleTG_envBoundH'),
 ('rank h+1, any depth n', 'ParentBounds.2: Bounded (weS o) s.st', 'hst (premise of svBoundsH_of_checks)', 'svBoundsH_of_checks'),
 ('rank h+1, n = 0, each instance', 'LeafBounds(kid).1: connSeed bounded', 'connEnvS_bound + hpm + envAt_bound (inside svBoundsH_of_checks, zero case)', 'svBoundsH_of_checks'),
 ('rank h+1, n = 0, each instance', 'LeafBounds(kid).2: kid start state bounded', 'InvN C 0 gc (s.kids iname) (premise hkids)', 'InvN'),
 ('rank h+1, n = m+1, each instance, each kid run', 'SVBoundsH C rk m child ... (recursive)', 'induction hypothesis of svBoundsH_of_checks at the kid rank r<=h from hcheck edges (hcheck_succ_iff)', 'svBoundsH_of_checks'),
 ('uniform -> height (K2)', 'SVBounds ==> SVBoundsH under hcheck and rank facts', 'svBoundsH_of_svBounds', 'svBoundsH_of_svBounds'),
 ('instance topshareM (rank 3, n=2)', 'whole SVBoundsH', 'topshareM_svBoundsH from topshareM_hcheck + hseedB/hst/hkids premises', 'topshareM_svBoundsH'),
 ('instance topshareQ (rank 2, n=1)', 'whole SVBoundsH', 'topshareQ_svBoundsH from topshareQ_hcheck + hseedB/hst/hkids premises', 'topshareQ_svBoundsH'),
 ('machine side: hseedB, hst, hkids (InvN of instance states)', 'width facts of the top seeding / start state / instance start states', 'MISSING here (PREMISE of the new theorems; svBounds_of_checks takes the same three)', None),
]
for (case, conj, how, decl) in ROWS:
    if decl is None:
        print(f'{case}\t{conj}\tMISSING\t{how}')
    else:
        print(f'{case}\t{conj}\t{SUP(decl)}\t{how}')
