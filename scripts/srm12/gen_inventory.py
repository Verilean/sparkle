#!/usr/bin/env python3
"""SRM12 inventory table.  Usage: gen_inventory.py RAW.txt > INVENTORY.md
RAW.txt = the EDGE/DESIGN/MODULE/INST lines printed by scripts/srm12/Inventory.lean
(run: ./.cluster/qbuild.sh env lean scripts/srm12/Inventory.lean | grep -E '^(EDGE|DESIGN|MODULE|INST)' > RAW.txt).
Section (c) lists existing lemmas and CHECKS that each is declared in the named file (a missing one aborts)."""
import re, sys, pathlib
raw = pathlib.Path(sys.argv[1]).read_text().splitlines()
short = lambda s: s.replace("Tests.Compiler.SharedLeafMemKidTest.", "").replace("Tests_Compiler_SharedLeafMemKidTest_", "")
out = ["# SRM12 inventory (generated by scripts/srm12/gen_inventory.py from the compiler run; not a proof)", ""]
out += ["## (a) CallGraph edges (caller, kid, origin) read from `X.machineData.shape.instTagged`", "",
        "| caller | kid | origin |", "|---|---|---|"]
for l in raw:
    m = re.match(r"EDGE caller=(\S+) kid=(\S+) origin=Sparkle.Compiler.MachInstOrigin.InstOrigin\.(.*)", l)
    if m: out.append(f"| {short(m[1])} | {short(m[2])} | {m[3]} |")
out += ["", "## (b) Instance statements of every module of the compiled design (top module + `D.modules`)", ""]
design = None
for l in raw:
    if l.startswith("DESIGN"):
        design = short(l.split()[1].rstrip(":")); out += ["", f"### design {design}", "", "| module | decoded | instance name | target module | target decoded |", "|---|---|---|---|---|"]
    m = re.match(r"INST module=(\S+) iname=(\S+) target=(\S+) \[(.*)\]", l)
    if m: out.append(f"| {short(m[1])} | | {short(m[2])} | {short(m[3])} | {short(m[4])} |")
    m = re.match(r"MODULE (\S+) \[(.*)\](.*)", l)
    if m: out.append(f"| **{short(m[1])}**{m[3]} | {short(m[2])} | | | |")
out += ["", "Note: four call entries of `topshareM` (`wrapM`×2, `wrapM3`×2) compile to TWO instance statements (one per callee group, `closeInstsG`); the correspondence is therefore on target SETS, not on counts.", ""]
lem = [
 ("closeInsts_calls", "Tools/ShippingMachineInst.lean", "every call k has an instance statement `CallStmt … mc` of the closed module, `children[k] = child`, `mc` = child resolved in the merged design"),
 ("closeInsts_insts", "Tools/ShippingMachineInst.lean", "every instance statement of the closed module is a pre-existing one or a call statement"),
 ("closeInstsG_calls", "Tools/ShippingMachineInstG.lean", "G (grouped) closing: every call k is served by an instance statement `CallStmtG`; `(children[k]).map name = child.1.name`"),
 ("closeInstsG_insts", "Tools/ShippingMachineInstG.lean", "G closing: every instance statement is a call-group statement"),
 ("closeInstsG_names", "Tools/ShippingMachineInstG.lean", "children resolve in the merged design as themselves"),
 ("moduleByName_name", "Tools/ShippingMachineInst.lean", "`moduleByName ms nm = some mc → mc.name = nm` (`mn = mc.name`)"),
 ("inst_target_ranA", "Tools/ShippingSrm5Ident.lean", "instance statement of a run's module names `y.1.name` for the child `y` of some call k (memory origin: `child? = some y`; else `RealChildA`)"),
 ("core_kids_facts_ranAM", "Tools/ShippingSrm3Iface.lean", "`M.name = ofDecl c`, `b.body = M.body`, every module of D comes from a kid (`KidTA`)"),
 ("kidTA_ofO", "Tools/ShippingSrm4Core1.lean", "child of the general closing is the tag-based kid `KidTA`"),
 ("checkedOptimize_inst_iff_gate", "Tools/ShippingChecksDepthGate.lean", "optimisation keeps the instance statements (under `hierGate`)"),
 ("core_hierGate_anyAM", "Tools/ShippingSrm4Core2.lean", "`hierGate b = true` (memory-aware)"),
 ("memModule_name", "Tools/ShippingMemOnlyNames.lean", "`(memModule cb aw dw).1.name = ofMem cb aw dw`"),
 ("hcheck_edge", "Tools/ShippingSrm5Height.lean", "SRM5: `mn = child.name`, `rk mn = some r`, `r ≤ h` for every instance statement of a ranked module (consumed form of the correspondence)"),
 ("rkOf_edge", "Tools/ShippingSrm7Rank.lean", "SRM7: every call entry of a ranked declaration has module rank `< r` (graph side)"),
 ("deepChild_ranAM", "Tools/ShippingSrm4Core5.lean", "a `RealChildA` of a callee is the post-processed module of a `MachineRanA` of that callee, `y.2.modules = D.modules`"),
]
out += ["## (c) Existing lemmas relating machineData calls to emitted instances (existence checked against the source)", "", "| lemma | file | content |", "|---|---|---|"]
root = pathlib.Path(__file__).resolve().parents[2]
for n, f, c in lem:
    txt = (root / f).read_text()
    if not re.search(r"(theorem|def)\s+" + re.escape(n) + r"\b", txt):
        sys.exit(f"MISSING lemma {n} in {f}")
    out.append(f"| `{n}` | {f} | {c} |")
out += ["", "Also: `ChildIfaceP.name` (Tools/ShippingMemClosesKids.lean) gives `y.1.name = nm` for the ordinary kids (`mn = (children[k]).1.name` is `closeInstsG_calls`/`inst_target_ranA`)."]
print("\n".join(out))
