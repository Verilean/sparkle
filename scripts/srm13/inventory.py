#!/usr/bin/env python3
"""SRM13 M1: machine-generated inventory.
Usage (repo root): python3 -I scripts/srm13/inventory.py > scripts/srm13/INVENTORY.txt
Part 1: exact source header (name .. binders .. conclusion, up to ':=') of the relevant declarations, with file:line (found by scanning Tools/ and Tests/).
Part 2: one row per premise x instance: the candidate supplier (declaration located by the scan) and the status.  The script FAILS if a cited declaration is not found."""
import re, os, sys
DECLS = ['Bounded', 'weS', 'InvN', 'KT', 'KSn', 'KState', 'KidState', 'ResetN', 'ResetNk', 'Reset1', 'seedIn', 'kidsInit', 'kidsInit_sat', 'kidsZero', 'regInitOf', 'runModuleTG', 'stepModuleTG',
         'svBoundsH_of_checks', 'topshareM_svBoundsH', 'topshareQ_svBoundsH', 'topshareM_designSVH_noB', 'topshareQ_designSVH_noB', 'moduleByName_of_childMap', 'checkedOptimize_ports',
         'seedB_of_seedIn', 'seedB_checkedOptimize', 'seedIn_not_bounded', 'hseedB_not_forced', 'RegsAtInit', 'RegsFit', 'NonRegBounded', 'bounded_of_regsAtInit', 'bounded_not_forced',
         'invN0_not_forced', 'FitTree', 'invN_of_resetN_fitTree', 'kidReset_of_resetNk', 'kidInvN_of_resetNk', 'topshareM_svBoundsH_viaReset', 'topshareQ_svBoundsH_viaReset',
         'topshareM_designSVH_viaReset', 'topshareQ_designSVH_viaReset']
HDR = re.compile(r'^\s*(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+|noncomputable\s+)*(theorem|lemma|def|abbrev|structure)\s+(\S+)')
found = {}
for root in ['Tools', 'Tests', 'Sparkle']:
    for dp, _, fs in sorted(os.walk(root)):
        if '/.lake' in dp: continue
        for f in sorted(fs):
            if not f.endswith('.lean'): continue
            p = os.path.join(dp, f)
            lines = open(p, encoding='utf-8', errors='replace').read().split('\n')
            for i, l in enumerate(lines):
                m = HDR.match(l)
                if m and m.group(2).split('.')[-1] in DECLS:
                    nm = m.group(2).split('.')[-1]
                    hdr = []
                    for j in range(i, min(i + 40, len(lines))):
                        s = lines[j]
                        if j > i and re.match(r'^\s*\|', s): break
                        hdr.append(s.strip())
                        if ':=' in s and not s.strip().startswith('--'): break
                    found.setdefault(nm, []).append((p, i + 1, ' '.join(hdr)[:900]))
def where(n):
    if n not in found:
        print('MISSING DECL', n, file=sys.stderr); sys.exit(1)
    return found[n]
print('# SRM13 M1 inventory (GENERATED by scripts/srm13/inventory.py; do not edit)')
print('## Part 1: exact headers')
for n in DECLS:
    for (p, ln, h) in where(n):
        print(f'{n}\t{p}:{ln}\t{h}')
def loc(n):
    p, ln, _ = where(n)[0]
    return f'{p}:{ln}'
ROWS = [
 ('hseedB', 'topshareM', 'SUPPLIED modulo the input range `hin` (a machine-bridge premise)', ['seedB_checkedOptimize', 'seedB_of_seedIn', 'seedIn', 'checkedOptimize_ports', 'topshareM_svBoundsH_viaReset', 'topshareM_designSVH_viaReset']),
 ('hseedB', 'topshareQ', 'SUPPLIED modulo the input range `hin` (a machine-bridge premise)', ['seedB_checkedOptimize', 'seedB_of_seedIn', 'seedIn', 'checkedOptimize_ports', 'topshareQ_svBoundsH_viaReset', 'topshareQ_designSVH_viaReset']),
 ('hst', 'topshareM', 'MISSING: RegsAtInit + RegsFit + NonRegBounded (sufficient: bounded_of_regsAtInit); Reset fixes registers only', ['bounded_of_regsAtInit', 'RegsAtInit', 'RegsFit', 'NonRegBounded', 'bounded_not_forced', 'ResetN', 'topshareM_svBoundsH_viaReset']),
 ('hst', 'topshareQ', 'MISSING: RegsAtInit + RegsFit + NonRegBounded (sufficient: bounded_of_regsAtInit); Reset fixes registers only', ['bounded_of_regsAtInit', 'RegsAtInit', 'RegsFit', 'NonRegBounded', 'bounded_not_forced', 'ResetN', 'topshareQ_svBoundsH_viaReset']),
 ('hkids', 'topshareM', 'MISSING: ResetNk (machine reset) + hO + FitTree per instance (sufficient: kidInvN_of_resetNk)', ['kidInvN_of_resetNk', 'invN_of_resetN_fitTree', 'kidReset_of_resetNk', 'FitTree', 'ResetNk', 'invN0_not_forced', 'kidsInit_sat', 'topshareM_svBoundsH_viaReset']),
 ('hkids', 'topshareQ', 'MISSING: ResetNk (machine reset) + hO + FitTree per instance (sufficient: kidInvN_of_resetNk)', ['kidInvN_of_resetNk', 'invN_of_resetN_fitTree', 'kidReset_of_resetNk', 'FitTree', 'ResetNk', 'invN0_not_forced', 'kidsInit_sat', 'topshareQ_svBoundsH_viaReset']),
]
print('## Part 2: premise x instance (supplier locations from the scan)')
for (prem, inst, status, sups) in ROWS:
    print(f'{prem}\t{inst}\t{status}\t' + '; '.join(f'{s}@{loc(s)}' for s in sups))
print('## Part 3: how the premises are bound in the SRM11 instance theorems')
print('seed, s : universally quantified binders `(seed : Nat → (String → Nat) → Env) (s : KState (KT n))`, linked only by `hrun : runModuleTG ... seed T\' s = some envs`; nothing ties them to seedIn or to a Reset state.')
print('machine run (Tools/ShippingSrm8Bridge.lean): the stream is `seedIn b ins`, the start state `⟨st0, mems, kids⟩` with `Reset raw D kids`, `st0 r = f.init` on the slot registers, inputs bounded `ins t x < 2 ^ declWidth b x`.')
